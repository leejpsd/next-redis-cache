import type { ReactNode } from "react";
import type { RandomUserPayload } from "@/app/lib/getRandomUser";

type RuntimeIdentity = {
  instanceId: string;
};

type ExperimentSnapshotProps = {
  eyebrow: string;
  title: string;
  description: string;
  strategySummary: string;
  payload: RandomUserPayload;
  renderer: RuntimeIdentity | null;
  children?: ReactNode;
};

function formatServedAt(timestamp: number): string {
  return new Date(timestamp).toLocaleString("ko-KR", {
    month: "numeric",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });
}

export function ExperimentSnapshot({
  eyebrow,
  title,
  description,
  strategySummary,
  payload,
  renderer,
  children,
}: ExperimentSnapshotProps) {
  const user = payload.results[0];
  const fullName = `${user.name.title} ${user.name.first} ${user.name.last}`;
  const servedAt = formatServedAt(payload.fetchedAt);

  return (
    <main className="app-shell min-h-screen px-4 py-6 sm:px-6 sm:py-7 lg:px-8">
      <div className="mx-auto flex w-full max-w-5xl flex-col gap-5">
        <section className="glass-card rounded-[2rem] px-6 py-6 sm:px-7">
          <div className="flex flex-col gap-5">
            <div className="space-y-2">
              <p className="eyebrow">{eyebrow}</p>
              <h1 className="text-3xl font-semibold tracking-[-0.05em] text-stone-950 sm:text-[3rem] sm:leading-[1.04]">
                {title}
              </h1>
              <p className="max-w-3xl text-sm leading-6 text-stone-600 sm:text-[0.95rem]">
                {description}
              </p>
            </div>

            <div className="grid gap-4 md:grid-cols-[minmax(0,1.2fr)_minmax(260px,0.8fr)]">
              <div className="metric-card rounded-[1.6rem] p-5">
                <p className="text-[0.72rem] font-semibold uppercase tracking-[0.16em] text-stone-500">
                  Strategy Summary
                </p>
                <p className="mt-2 text-sm leading-6 text-stone-700">
                  {strategySummary}
                </p>
                {children ? <div className="mt-4">{children}</div> : null}
              </div>

              <div className="metric-card rounded-[1.6rem] p-5">
                <p className="text-[0.72rem] font-semibold uppercase tracking-[0.16em] text-stone-500">
                  Runtime
                </p>
                <dl className="mt-3 space-y-3 text-sm text-stone-700">
                  <div>
                    <dt className="text-[11px] uppercase tracking-[0.14em] text-stone-500">
                      Rendered By
                    </dt>
                    <dd className="mt-1 break-all font-mono text-[13px]">
                      {renderer?.instanceId ?? "browser"}
                    </dd>
                  </div>
                  <div>
                    <dt className="text-[11px] uppercase tracking-[0.14em] text-stone-500">
                      Generated By
                    </dt>
                    <dd className="mt-1 break-all font-mono text-[13px]">
                      {payload.generatedBy.instanceId}
                    </dd>
                  </div>
                  <div>
                    <dt className="text-[11px] uppercase tracking-[0.14em] text-stone-500">
                      Served At
                    </dt>
                    <dd className="mt-1 font-medium text-stone-900">{servedAt}</dd>
                  </div>
                </dl>
              </div>
            </div>
          </div>
        </section>

        <section className="glass-card rounded-[2rem] px-6 py-6 sm:px-7">
          <div className="grid gap-6 md:grid-cols-[120px_minmax(0,1fr)] md:items-center">
            <div className="flex h-[120px] w-[120px] items-center justify-center rounded-full bg-stone-100 text-3xl font-semibold text-stone-500 ring-1 ring-stone-300/80 ring-offset-4 ring-offset-[#f7f2ea]">
              {user.name.first.slice(0, 1)}
              {user.name.last.slice(0, 1)}
            </div>

            <div className="space-y-2">
              <p className="text-[0.72rem] font-semibold uppercase tracking-[0.16em] text-stone-500">
                Random User Snapshot
              </p>
              <h2 className="text-3xl font-semibold tracking-[-0.04em] text-stone-950">
                {fullName}
              </h2>
              <p className="text-sm text-stone-600">
                {user.nat} · 나이 {user.dob.age}세 · 가입 {user.registered.age}년차
              </p>
              <p className="text-sm leading-6 text-stone-700">
                이 페이지는 같은 데이터셋을 유지한 채 렌더링 전략만 바꿔서
                비교하기 위한 실험용 스냅샷입니다.
              </p>
            </div>
          </div>
        </section>

        <pre id="experiment-random-user-payload" className="sr-only">
          {JSON.stringify(payload)}
        </pre>
        <pre id="experiment-renderer" className="sr-only">
          {JSON.stringify(renderer)}
        </pre>
      </div>
    </main>
  );
}
